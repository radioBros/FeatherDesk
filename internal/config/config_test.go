func env(m map[string]string) func(string) string { return func(k string) string { return m[k] } }

const key32 = "MDEyMzQ1Njc4OTAxMjM0NTY3ODkwMTIzNDU2Nzg5MDE=" // 32 bytes base64

func TestDefaults(t *testing.T) {
	c, err := Load(env(map[string]string{"ST_SECRET_KEY": key32}))
	if err != nil {
		t.Fatal(err)
	}
	if c.ListenAddr != ":8080" || c.DBReaders != 2 || c.ShutdownTimeout != 20*time.Second || !c.MigrateOnBoot {
		t.Fatalf("defaults wrong: %+v", c)
	}
	if c.AgentURL != "http://localhost:8080/agent" || len(c.SecretKey) != 32 {
		t.Fatalf("derived wrong: %q %d", c.AgentURL, len(c.SecretKey))
	}
	if c.EffectiveDatabaseURL() != "sqlite:///data/simpletickets.db" {
		t.Fatal(c.EffectiveDatabaseURL())
	}
}

func TestAllErrorsAtOnce(t *testing.T) {
	_, err := Load(env(map[string]string{
		"ST_PUBLIC_URL":      "not a url",
		"ST_DB_READERS":      "x",
		"ST_LOG_LEVEL":       "loud",
		"ST_TRUSTED_PROXIES": "10.0.0.0/8,nope",
	}))
	var le *LoadError
	if !errors.As(err, &le) {
		t.Fatalf("want LoadError, got %v", err)
	}
	msg := err.Error()
	for _, want := range []string{"ST_PUBLIC_URL", "ST_DB_READERS", "ST_LOG_LEVEL", "ST_TRUSTED_PROXIES", "ST_SECRET_KEY"} {
		if !strings.Contains(msg, want) {
			t.Errorf("missing %s in:\n%s", want, msg)
		}
	}
}

func TestDevGeneratesSecret(t *testing.T) {
	dir := t.TempDir()
	c, err := Load(env(map[string]string{"ST_DEV": "true", "ST_DATA_DIR": dir}))
	if err != nil {
		t.Fatal(err)
	}
	c2, err := Load(env(map[string]string{"ST_DEV": "true", "ST_DATA_DIR": dir}))
	if err != nil {
		t.Fatal(err)
	}
	if string(c.SecretKey) != string(c2.SecretKey) {
		t.Fatal("dev secret must persist across restarts")
	}
}

func TestDevRefusedOnPublicHTTPS(t *testing.T) {
	_, err := Load(env(map[string]string{"ST_DEV": "true", "ST_DATA_DIR": t.TempDir(), "ST_PUBLIC_URL": "https://help.example.com"}))
	if err == nil || !strings.Contains(err.Error(), "ST_DEV") {
		t.Fatalf("want ST_DEV refusal, got %v", err)
	}
}

func TestRedacted(t *testing.T) {
	c, _ := Load(env(map[string]string{"ST_SECRET_KEY": key32, "ST_DATABASE_URL": "postgres://u:hunter2@db/x"}))
	r := c.Redacted()
	if r["ST_SECRET_KEY"] != "***" || strings.Contains(r["ST_DATABASE_URL"], "hunter2") {
		t.Fatalf("not redacted: %v", r)
	}
}

func TestEnvHelpers(t *testing.T) {
	e := NewEnv(env(map[string]string{"A": "5", "B": "x", "M": "g1=admin, g2=agent", "D": "3s"}))
	if e.Int("A", 0) != 5 || e.Duration("D", 0) != 3*time.Second {
		t.Fatal("parse")
	}
	e.Int("B", 1)
	m := e.Map("M")
	if m["g2"] != "agent" {
		t.Fatal(m)
	}
	e.Required("MISSING")
	if err := e.Err(); err == nil || !strings.Contains(err.Error(), "B") || !strings.Contains(err.Error(), "MISSING") {
		t.Fatalf("errs: %v", err)
	}
}

// TestConfigDocInSync keeps docs/configuration.md's generated core table current.
func TestConfigDocInSync(t *testing.T) {
	b, err := os.ReadFile("../../docs/configuration.md")
	if err != nil {
		t.Fatal(err)
	}
	doc := string(b)
	const begin, end = "<!-- BEGIN CORE (generated by config.Markdown; TestConfigDocInSync) -->\n", "<!-- END CORE -->"
	i, j := strings.Index(doc, begin), strings.Index(doc, end)
	if i < 0 || j < 0 {
		t.Fatal("markers missing in docs/configuration.md")
	}
	if got := doc[i+len(begin) : j]; got != Markdown() {
		t.Fatalf("docs/configuration.md core table is stale; replace it with:\n%s", Markdown())
	}
}
